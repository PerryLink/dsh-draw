/**
 * Plugin configuration for `dsh-draw` and its explicit resolve step.
 * `resolveConfig` re-judges every default and bound so programmatic
 * construction that bypasses Schemastery normalization still fails loud
 * instead of running with hidden defaults (the explicit-resolve contract).
 *
 * @module dsh-draw/config
 */

import z from '@deepseek-ai/schemastery'
import type { ImageMediaType } from '@deepseek-ai/dsh-attachment'

/** Default per-generation HTTP timeout in milliseconds. */
export const DEFAULT_REQUEST_TIMEOUT_MS = 120_000

/** Ceiling for one generation call: engines can take minutes per image. */
export const MAX_REQUEST_TIMEOUT_MS = 600_000

/** Default cap on images a single call may produce. */
export const DEFAULT_MAX_IMAGES_PER_CALL = 4

/** Ceiling on images a single call may produce. */
export const MAX_IMAGES_PER_CALL = 10

/** Default prompt length cap (characters). */
export const DEFAULT_MAX_PROMPT_LENGTH = 4_000

/** Ceiling on the prompt length cap. */
export const MAX_PROMPT_LENGTH = 32_000

/** Default per-session generation-call cap. */
export const DEFAULT_MAX_GENERATIONS_PER_SESSION = 200

/** Ceiling on the per-session generation-call cap. */
export const MAX_GENERATIONS_PER_SESSION = 100_000

/** Default per-session image-byte cap (200 MiB). */
export const DEFAULT_MAX_BYTES_PER_SESSION = 200 * 1024 * 1024

/** Ceiling on the per-session image-byte cap (4 GiB). */
export const MAX_BYTES_PER_SESSION = 4 * 1024 * 1024 * 1024

/** Default consecutive failures before an engine enters cooldown. */
export const DEFAULT_FAILURE_THRESHOLD = 2

/** Ceiling on the consecutive-failure threshold. */
export const MAX_FAILURE_THRESHOLD = 10

/** Default engine cooldown after the failure threshold trips (ms). */
export const DEFAULT_COOLDOWN_MS = 60_000

/** Ceiling on the engine cooldown. */
export const MAX_COOLDOWN_MS = 3_600_000

/** Standard size vocabulary mapped per engine through {@link EngineConfig.sizeMap}. */
export type StandardSize = 'square' | 'landscape' | 'portrait' | 'auto'

/** Per-engine mapping from the standard size vocabulary to concrete engine sizes. */
export interface EngineSizeMap {
  /** Square composition (the default). */
  square: string
  /** Wider-than-tall composition. */
  landscape: string
  /** Taller-than-wide composition. */
  portrait: string
  /** Engine-chosen composition; may alias one of the concrete sizes. */
  auto: string
}

/** Whether generated images arrive as base64 payloads or downloadable URLs. */
export type EngineResponseFormat = 'b64_json' | 'url'

/** The image-generation vocabularies a configured engine may declare (provider seam). */
export type EngineVocabulary = 'openai' | 'replicate' | 'fal'

/** One OpenAI-compatible image-generation endpoint the router may use. */
export interface EngineConfig {
  /** Stable engine id used in tool args, results, and the settings panel. */
  id: string
  /** OpenAI-compatible API root, e.g. `https://api.openai.com/v1`; must not embed credentials. */
  baseUrl: string
  /** Engine model name sent in the request body, e.g. `gpt-image-1`. */
  model: string
  /** Credential reference (environment-variable name) the API key resolves from; never a literal key. */
  apiKeyRef: string
  /** Which request/response vocabulary this engine speaks (default `openai`). */
  provider?: EngineVocabulary
  /** Whether the router may use this engine (default true). */
  enabled?: boolean
  /** Standard-size → concrete-size translation (default: the OpenAI sizes). */
  sizeMap?: EngineSizeMap
  /** Whether the engine accepts the `quality` request field (default false). */
  qualitySupported?: boolean
  /** Whether the engine accepts the `style` request field (default false). */
  styleSupported?: boolean
  /** How generated bytes arrive: base64 in the response or a URL to download (default `b64_json`). */
  responseFormat?: EngineResponseFormat
  /** Declared media type of the bytes (default `image/png`). */
  imageMediaType?: ImageMediaType
}

/** Plugin configuration. */
export interface Config {
  /** Ordered engine chain; the router walks it top-down and falls back on failure. */
  engines?: EngineConfig[]
  /** Engine id the router prefers; defaults to the first configured engine. Must name a configured engine. */
  defaultEngine?: string
  /** Per-generation HTTP timeout in milliseconds (default 120000). */
  requestTimeoutMs?: number
  /** Cap on images one call may produce (default 4). */
  maxImagesPerCall?: number
  /** Prompt length cap in characters (default 4000). */
  maxPromptLength?: number
  /** Per-session generation-call cap (default 200). */
  maxGenerationsPerSession?: number
  /** Per-session generated-image byte cap (default 209715200). */
  maxBytesPerSession?: number
  /** Consecutive failures before an engine enters cooldown (default 2). */
  failureThreshold?: number
  /** Engine cooldown in milliseconds after the failure threshold trips (default 60000). */
  cooldownMs?: number
}

